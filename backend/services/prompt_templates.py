def get_file_upload_success(model: Optional[str] = None, brand: Optional[str] = None, power: Optional[float] = None) -> List[str]:
    """Сообщение об успешном извлечении данных из файла."""
    parts = ["Извлёк данные из файла:\n"]
    
    if model:
        parts.append(f"Модель: {model}")
    if brand:
        parts.append(f"Бренд: {brand}")
    if power:
        parts.append(f"Мощность: {power} кВт")
    
    if model:
        parts.append(f"\nЯ правильно понял модель {model}?")
        parts.append("Если да, могу найти аналог или подобрать насос по параметрам.")
    else:
        parts.append("\nНе удалось извлечь модель. Попробуйте указать её вручную.")
    
    return parts


