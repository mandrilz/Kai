def normalize_text(text: str) -> str:
    """
    Нормализует текст: приводит к нижнему регистру, убирает лишние пробелы и пунктуацию.
    """
    if not text:
        return ""
    
    # Приводим к нижнему регистру
    text = text.lower().strip()
    
    # Убираем множественные пробелы
    text = re.sub(r'\s+', ' ', text)
    
    # Убираем лишние знаки пунктуации в начале и конце
    text = text.strip('.,!?;:')
    
    return text


def classify_short_answer(text: str) -> Dict[str, Any]:
    """
    Классифицирует короткий ответ пользователя.
    
    Args:
        text: Текст ответа пользователя
        
    Returns:
        Словарь с полями:
        - intent: категория ответа (NO, UNKNOWN, DONT_CARE, MAYBE, SKIP, OTHER)
        - normalized_text: нормализованный текст
    """
    normalized = normalize_text(text)
    
    if not normalized:
        return {
            "intent": "OTHER",
            "normalized_text": text
        }
    
    # Проверяем категории в порядке приоритета
    # SKIP имеет наивысший приоритет (явное указание пропустить)
    for phrase in SKIP_PHRASES:
        if phrase in normalized:
            return {
                "intent": "SKIP",
                "normalized_text": normalized
            }
    
    # NO - отрицание
    for phrase in NO_PHRASES:
        if phrase in normalized:
            return {
                "intent": "NO",
                "normalized_text": normalized
            }
    
    # UNKNOWN - не знаю
    for phrase in UNKNOWN_PHRASES:
        if phrase in normalized:
            return {
                "intent": "UNKNOWN",
                "normalized_text": normalized
            }
    
    # DONT_CARE - без разницы
    for phrase in DONT_CARE_PHRASES:
        if phrase in normalized:
            return {
                "intent": "DONT_CARE",
                "normalized_text": normalized
            }
    
    # MAYBE - сомнение
    for phrase in MAYBE_PHRASES:
        if phrase in normalized:
            return {
                "intent": "MAYBE",
                "normalized_text": normalized
            }
    
    # Если не найдено совпадений - возвращаем OTHER
    return {
        "intent": "OTHER",
        "normalized_text": normalized
    }
