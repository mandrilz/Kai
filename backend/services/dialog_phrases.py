def get_phrase(pool: list) -> str:
    """Возвращает случайную фразу из пула."""
    return random.choice(pool)


def combine_phrases(*phrases: str, sep: str = "\n") -> str:
    """Объединяет фразы с разделителем."""
    return sep.join([p for p in phrases if p])

