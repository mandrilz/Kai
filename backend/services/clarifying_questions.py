"""
Унифицированные уточняющие вопросы для slot filling.
Все вопросы централизованы здесь для единообразия и легкого обновления.
"""
from typing import Dict, Any, Optional
import random


def get_clarifying_question(slot: str, state: Dict[str, Any] = None) -> str:
    """
    Возвращает уточняющий вопрос для указанного слота.
    
    Args:
        slot: Название слота (flow_m3h, head_m, fluid, temperature_c и т.д.)
        state: Текущее состояние диалога (для контекстных вопросов)
    
    Returns:
        Текст вопроса
    """
    state = state or {}
    
    questions_map = {
        "flow_m3h": [
            "Какой расход жидкости требуется? (в м³/ч)",
            "Укажите расход в м³/ч",
            "Какой расход нужен? (м³/ч)",
        ],
        "head_m": [
            "Какой напор требуется? (в метрах)",
            "Укажите напор в метрах",
            "Какой напор нужен? (метры)",
        ],
        "fluid": [
            "Какая жидкость будет перекачиваться?",
            "Какой тип жидкости?",
            "Что будет перекачиваться?",
        ],
        "temperature_c": [
            "Какая температура жидкости? (в градусах Цельсия, °C)",
            "Укажите температуру в градусах Цельсия (°C)",
            "Какая температура? (обычно работаем в °C)",
        ],
        "viscosity": [
            "Какая вязкость жидкости? (если известна)",
            "Укажите вязкость (если известна)",
            "Какая вязкость? (опционально)",
        ],
        "concentration": [
            "Какая концентрация? (для этиленгликоля/антифриза)",
            "Укажите концентрацию",
            "Какая концентрация раствора?",
        ],
        "solids": [
            "Есть ли в жидкости твердые частицы или примеси?",
            "Содержит ли жидкость примеси?",
            "Есть ли твердые частицы?",
        ],
        "installation": [
            "Какой тип установки? (вертикальный/горизонтальный)",
            "Укажите тип установки",
            "Вертикальная или горизонтальная установка?",
        ],
        "materials": [
            "Какие материалы корпуса требуются? (A/E/X/H)",
            "Укажите материал корпуса",
            "Какой материал исполнения?",
        ],
        "h_st": [
            "Какой статический напор сети? (в метрах)",
            "Укажите статический напор",
            "Какой статический напор? (метры)",
        ],
    }
    
    # Получаем варианты вопросов для слота
    questions = questions_map.get(slot, [f"Укажите {slot}"])
    
    # Выбираем случайный вопрос для разнообразия
    question = random.choice(questions)
    
    # Специальная обработка для некоторых слотов
    if slot == "temperature_c":
        # Если температура уже была упомянута, но без знака
        if state.get("__temp_without_sign"):
            temp_value = state.get("__temp_without_sign")
            question = random.choice([
                f"{temp_value} °C верно? (или минус {temp_value} °C?)",
                f"Температура {temp_value} °C выше нуля или ниже?",
                f"Температура плюс {temp_value} °C или минус {temp_value} °C?",
            ])
        else:
            # Добавляем единицы по умолчанию
            question = question.replace("(в градусах Цельсия)", "(в градусах Цельсия, обычно работаем в °C)")
    
    if slot == "flow_m3h":
        # Добавляем единицы по умолчанию
        question = question.replace("(в м³/ч)", "(в м³/ч, обычно работаем в м³/ч)")
    
    if slot == "head_m":
        # Добавляем единицы по умолчанию
        question = question.replace("(в метрах)", "(в метрах, обычно работаем в метрах)")
    
    if slot == "fluid" and state.get("flow_m3h") and state.get("head_m"):
        # Если уже есть Q и H, вопрос о жидкости может быть более конкретным
        question = random.choice([
            "Какая жидкость будет перекачиваться?",
            "Какой тип жидкости? (вода, масло, химия и т.д.)",
            "Что будет перекачиваться?",
        ])
    
    return question


def get_follow_up_suggestion(intent: str, state: Dict[str, Any] = None) -> Optional[str]:
    """
    Возвращает предложение для продолжения диалога после ответа.
    
    Args:
        intent: Интент пользователя
        state: Текущее состояние диалога
    
    Returns:
        Текст предложения или None
    """
    state = state or {}
    
    suggestions = {
        "SELECTION_BY_POINT": [
            "Могу уточнить параметры жидкости для более точного подбора.",
            "Нужно уточнить температуру или другие параметры?",
        ],
        "ANALOG_BY_MODEL": [
            "Могу найти другие аналоги или сравнить характеристики.",
            "Нужна дополнительная информация по этому насосу?",
        ],
        "DOCUMENTATION": [
            "Могу построить график кривой или сравнить с другим насосом.",
            "Нужна дополнительная документация?",
        ],
    }
    
    suggestions_list = suggestions.get(intent, [])
    if suggestions_list:
        return random.choice(suggestions_list)
    
    return None
