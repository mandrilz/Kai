from typing import Dict, Any, List


def generate_followups(intent: str, state: Dict[str, Any]) -> List[str]:
    """
    MVP follow-ups: 1–3 предложений продолжения диалога.
    """
    intent = (intent or "").lower()

    if "selection_by_point" in intent:
        # Проверяем, не заполнена ли уже жидкость - если да, не спрашиваем о ней снова
        fluid = state.get("fluid")
        if fluid:
            # Жидкость уже указана, не спрашиваем о ней
            return [
                "Хотите, я построю график Q‑H для выбранного насоса?",
                "Есть ли ограничения по материалу (нерж. 304/316) или примесям?",
                "Нужно уточнить температуру или другие параметры жидкости?",
            ]
        else:
            # Жидкость не указана, но не спрашиваем здесь - это делает slot_extractor
            # Возвращаем только другие вопросы
            return [
                "Хотите, я построю график Q‑H для выбранного насоса?",
                "Есть ли ограничения по материалу (нерж. 304/316) или примесям?",
                "Нужно уточнить параметры жидкости (температура, вязкость)?",
            ]

    if "analog_by_model" in intent:
        return [
            "Хотите сравнить кривые Q‑H Кометта vs конкурент на одном графике?",
            "Уточните, пожалуйста, мощность/частоту вращения конкурента (если известно).",
            "Если у вас есть паспорт/фото шильдика — приложите, я уточню модель.",
        ]

    if "file_upload" in intent:
        return [
            "Подтвердите: я правильно прочитал бренд/модель/мощность?",
            "Какая рабочая точка (Q м³/ч и H м) нужна по вашему объекту?",
            "Хотите, я сразу подберу ближайший аналог Кометта?",
        ]

    if "diagnostics" in intent:
        return [
            "Какая жидкость, температура и режим работы (непрерывно/пуск-стоп)?",
            "Есть ли кавитация/шум/вибрация и какая высота всасывания?",
            "Хотите, я предложу замену на насос Кометта по рабочей точке?",
        ]

    # default
    return [
        "Какая у вас задача: подбор по рабочей точке или поиск аналога?",
        "Какая рабочая точка: Q (м³/ч) и H (м)?",
    ]


def ensure_followups(text: str, intent: str, state: Dict[str, Any]) -> str:
    """
    Добавляет follow-up блок ТОЛЬКО после ответа по делу.
    Правило: сначала ответ/варианты, потом 1 follow-up (не пачкой).
    """
    t = (text or "").strip()
    if not t:
        t = "Я Кометтик — инженер‑помощник Кометта."

    tail = t[-400:]
    
    # Проверяем, есть ли уже вопросы в тексте
    if "?" in tail:
        # Если есть вопросы, не добавляем followups - пользователь уже получил вопрос
        return t
    
    # Проверяем, есть ли в ответе реальный контент (не только вопросы)
    # Если ответ содержит результаты подбора, варианты насосов, графики и т.д. - добавляем follow-up
    has_content_indicators = any([
        "насос" in t.lower() and ("подобра" in t.lower() or "найден" in t.lower() or "рекоменд" in t.lower()),
        "график" in t.lower(),
        "аналог" in t.lower() and ("найден" in t.lower() or "подобран" in t.lower()),
        "лист данных" in t.lower() or "datasheet" in t.lower(),
    ])
    
    # Добавляем follow-up только если есть реальный контент (ответ по делу)
    if has_content_indicators:
        # Берем только ОДИН follow-up, не пачку
        items = generate_followups(intent, state)
        if items:
            # Выбираем наиболее релевантный follow-up
            follow_up = items[0]  # Первый follow-up обычно наиболее релевантный
            return t + "\n\n" + follow_up
    
    # Если нет контента - не добавляем follow-ups
    return t

