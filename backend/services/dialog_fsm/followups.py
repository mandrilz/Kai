from typing import Dict, Any, List


def generate_followups(intent: str, state: Dict[str, Any]) -> List[str]:
    """
    MVP follow-ups: 1–3 предложений продолжения диалога.
    """
    intent = (intent or "").lower()

    if "selection_by_point" in intent:
        return [
            "Какая жидкость и температура перекачиваемой среды?",
            "Хотите, я построю график Q‑H для выбранного насоса?",
            "Есть ли ограничения по материалу (нерж. 304/316) или примесям?",
        ]

    if "analog_by_model" in intent:
        return [
            "Хотите сравнить кривые Q‑H Кометта vs конкурент на одном графике?",
            "Уточните, пожалуйста, мощность/частоту вращения конкурента (если известно).",
            "Если у вас есть паспорт/фото шильдика — приложите, я уточню модель.",
        ]

    if "file_upload" in intent:
        return [
            "Подтвердите: я правильно прочитал бренд/модель/мощность?",
            "Какая рабочая точка (Q м³/ч и H м) нужна по вашему объекту?",
            "Хотите, я сразу подберу ближайший аналог Кометта?",
        ]

    if "diagnostics" in intent:
        return [
            "Какая жидкость, температура и режим работы (непрерывно/пуск-стоп)?",
            "Есть ли кавитация/шум/вибрация и какая высота всасывания?",
            "Хотите, я предложу замену на насос Кометта по рабочей точке?",
        ]

    # default
    return [
        "Какая у вас задача: подбор по рабочей точке или поиск аналога?",
        "Какая рабочая точка: Q (м³/ч) и H (м)?",
    ]


def ensure_followups(text: str, intent: str, state: Dict[str, Any]) -> str:
    """
    Добавляет follow-up блок, если в конце ответа нет явных вопросов.
    """
    t = (text or "").strip()
    if not t:
        t = "Я Кометтик — инженер‑помощник Кометта."

    tail = t[-400:]
    if "?" in tail:
        return t

    items = generate_followups(intent, state)[:3]
    return t + "\n\n" + "\n".join([f"— {q}" for q in items])

